MARKERS=frozenset(('.previous-release','.runtime-retention','.runtime-preservation','.activation-in-progress','.lock'))
class Refused(Exception):pass

def lexical(path):
    text=os.fspath(path)
    if not text.startswith('/') or any(x in ('.','..') for x in text.split('/')[1:]) or '\x00' in text or '\n' in text or '\r' in text:
        raise Refused('PATH_LEXICAL')
    return Path(text)

def trusted(st,kind):
    if not kind(st.st_mode):raise Refused('PATH_TYPE')
    if st.st_uid not in (0,os.geteuid()):raise Refused('PATH_OWNER')
    if st.st_mode & 0o022:raise Refused('PATH_WRITABLE')
    if stat.S_ISREG(st.st_mode) and st.st_nlink!=1:raise Refused('FILE_LINK_COUNT')

def directory(path):
    path=lexical(path)
    for item in list(reversed(path.parents))+[path]:trusted(item.lstat(),stat.S_ISDIR)
    return path

def release(live,path):
    live=lexical(live);parent=directory(Path(str(live)+'.releases'))
    if str(path)==str(live):
        directory(live.parent)
        if not stat.S_ISLNK(live.lstat().st_mode):return directory(live)
        value=os.readlink(live)
        target=Path(value) if value.startswith('/') else live.parent/value
    else:target=lexical(path)
    target=lexical(target)
    if target.parent!=parent:raise Refused('RELEASE_SCOPE')
    return directory(target)

def _budget(deadline):
    left=deadline-time.monotonic()
    if left<=0:raise Refused('TRUST_BUDGET')
    return left

def git_inputs(root,deadline):
    gd=directory(root/'.git');stack=[gd];seen=0
    while stack:
        _budget(deadline);folder=stack.pop()
        with os.scandir(folder) as entries:
            for entry in entries:
                _budget(deadline);seen+=1
                if seen>100000:raise Refused('GIT_INPUT_COUNT')
                st=entry.stat(follow_symlinks=False)
                if stat.S_ISDIR(st.st_mode):trusted(st,stat.S_ISDIR);stack.append(Path(entry.path))
                else:trusted(st,stat.S_ISREG)
    for external in (gd/'commondir',gd/'objects/info/alternates',gd/'info/grafts'):
        if os.path.lexists(external):raise Refused('EXTERNAL_GIT_STORE')
    config=gd/'config';st=config.lstat();trusted(st,stat.S_ISREG)
    if st.st_size>262144:raise Refused('GIT_CONFIG_BOUND')
    parser=configparser.ConfigParser(strict=False,interpolation=None)
    try:
        parser.read_string(config.read_text(encoding='utf-8'))
        for section in parser.sections():
            lower=section.lower()
            if lower.startswith(('include','url ')) or lower=='extensions' or (lower.startswith('remote ') and parser.has_option(section,'promisor')):raise Refused('GIT_CONFIG_EXTERNAL')
            if lower.startswith('filter '):raise Refused('GIT_CONFIG_EXTERNAL')
            if lower=='core' and (parser.has_option(section,'attributesfile') or parser.has_option(section,'excludesfile')):raise Refused('GIT_CONFIG_EXTERNAL')
            if lower=='core' and (parser.has_option(section,'worktree') or parser.get(section,'bare',fallback='false').strip().lower() not in ('false','no','0','off')):
                raise Refused('GIT_WORKTREE_CONFIG')
    except (ValueError,UnicodeError,configparser.Error):raise Refused('GIT_CONFIG_SHAPE') from None
    _budget(deadline)

def group_alive(pgid):
 try:os.killpg(pgid,0)
 except ProcessLookupError:return False
 except (PermissionError,OSError):raise Refused('GIT_PROCESS_GROUP_STATUS_UNKNOWN') from None
 return True

def stop_owned_group(p):
 deadline=time.monotonic()+2
 alive=group_alive(p.pid)
 if time.monotonic()>=deadline:raise Refused('GIT_PROCESS_GROUP_CLEANUP_UNKNOWN')
 if alive:
  try:os.killpg(p.pid,signal.SIGKILL)
  except ProcessLookupError:pass
 left=deadline-time.monotonic()
 if left<=0:raise Refused('GIT_PROCESS_GROUP_CLEANUP_UNKNOWN')
 p.wait(timeout=left)
 if time.monotonic()>=deadline:raise Refused('GIT_PROCESS_GROUP_CLEANUP_UNKNOWN')
 while group_alive(p.pid):
  left=deadline-time.monotonic()
  if left<=0:raise Refused('GIT_PROCESS_GROUP_CLEANUP_UNKNOWN')
  time.sleep(min(.01,left))
 if time.monotonic()>=deadline:raise Refused('GIT_PROCESS_GROUP_CLEANUP_UNKNOWN')
 return alive

def _capture(argv,env,budget=30,output_cap=32768):
 started=time.monotonic();deadline=started+budget;p=None;sel=None;out=bytearray();err=bytearray()
 try:
  p=subprocess.Popen(argv,env=env,stdin=subprocess.DEVNULL,stdout=subprocess.PIPE,stderr=subprocess.PIPE,start_new_session=True)
  if time.monotonic()>=deadline:raise Refused('GIT_PROCESS_TIMEOUT')
  sel=selectors.DefaultSelector();sel.register(p.stdout,selectors.EVENT_READ,'out');sel.register(p.stderr,selectors.EVENT_READ,'err')
  while sel.get_map():
   left=deadline-time.monotonic()
   if left<=0:raise Refused('GIT_PROCESS_TIMEOUT')
   ready=sel.select(left)
   if time.monotonic()>=deadline:raise Refused('GIT_PROCESS_TIMEOUT')
   for key,_ in ready:
    if time.monotonic()>=deadline:raise Refused('GIT_PROCESS_TIMEOUT')
    b=os.read(key.fileobj.fileno(),1024)
    if not b:sel.unregister(key.fileobj);continue
    (out if key.data=='out' else err).extend(b)
    if len(out)+len(err)>output_cap:raise Refused('GIT_PROCESS_OUTPUT_CAP')
  try:code=p.wait(timeout=max(.001,deadline-time.monotonic()))
  except subprocess.TimeoutExpired:raise Refused('GIT_PROCESS_TIMEOUT') from None
  if time.monotonic()>=deadline:raise Refused('GIT_PROCESS_TIMEOUT')
  return code,bytes(out),bytes(err)
 finally:
  primary=sys.exc_info()[1];cleanup_unknown=False
  if sel is not None:
   try:sel.close()
   except BaseException:cleanup_unknown=True
  if p is not None:
   try:
    had_members=stop_owned_group(p)
    if primary is None and had_members:primary=Refused('GIT_PROCESS_DESCENDANTS_REMAINED')
   except BaseException:cleanup_unknown=True
   for stream in (p.stdout,p.stderr):
    if stream is not None:
     try:stream.close()
     except BaseException:cleanup_unknown=True
  if cleanup_unknown:
   error=Refused('GIT_PROCESS_CLEANUP_UNKNOWN')
   error.primary_code=str(primary) if isinstance(primary,Refused) else 'UNEXPECTED_CAPTURE_FAILURE' if primary else None
   raise error from None
  if primary is not None and sys.exc_info()[1] is None:raise primary

def _git(root,args,deadline,cap=8192,network=False,command_timeout=3,home=None):
    env={'PATH':'/usr/bin:/bin','LANG':'C','LC_ALL':'C','GIT_CONFIG_NOSYSTEM':'1','GIT_CONFIG_GLOBAL':'/dev/null','GIT_NO_LAZY_FETCH':'1','GIT_NO_REPLACE_OBJECTS':'1','GIT_OPTIONAL_LOCKS':'0','GIT_TERMINAL_PROMPT':'0','GIT_ASKPASS':'/bin/false'}
    if args and args[0] in ('fetch','push','clone','remote') and not (network and args[0]=='fetch'):raise Refused('GIT_NETWORK_OPERATION')
    if network:
        if home is None:raise Refused('FETCH_ENVIRONMENT')
        env['HOME']=str(home)
        for key in ('HTTPS_PROXY','HTTP_PROXY','ALL_PROXY','NO_PROXY','https_proxy','http_proxy','all_proxy','no_proxy'):
            if key in os.environ:env[key]=os.environ[key]
    cmd=['/usr/bin/git','--no-pager','-c','credential.helper=','-c','core.askPass=/bin/false','-c','http.followRedirects=false','-c','http.extraHeader=','-c','http.cookieFile=/dev/null','-c','http.saveCookies=false','-c','protocol.allow=never','-c','protocol.https.allow=always','-c','submodule.recurse=false','-c','core.fsmonitor=false','-c','core.hooksPath=/dev/null','-c','core.pager=cat','-c','log.showSignature=false','-c','safe.directory='+str(root),'-C',str(root)]+args
    try:code,out,err=_capture(cmd,env,budget=min(command_timeout,_budget(deadline)),output_cap=cap)
    except Refused:raise
    except BaseException:raise Refused('GIT_COMMAND') from None
    _budget(deadline)
    if code or (err and not network) or len(out)+len(err)>cap:raise Refused('GIT_COMMAND')
    try:return out.decode('utf-8').strip()
    except UnicodeError:raise Refused('GIT_COMMAND') from None

def tracked_target(root,path,data,tracked):
    # Component-wise resolution: never descend into an external/unsafe link.
    seen=set();base=list(path.parent.relative_to(root).parts);parts=list(Path(os.fsdecode(data)).parts)
    if parts and parts[0]=='/':
        prefix=list(root.parts)
        if parts[:len(prefix)]!=prefix:raise Refused('EXTERNAL_TRACKED_TARGET')
        base=[];parts=parts[len(prefix):]
    while parts:
        part=parts.pop(0)
        if part in ('','.'):continue
        if part=='..':
            if not base:raise Refused('EXTERNAL_TRACKED_TARGET')
            base.pop();continue
        target=root.joinpath(*base,part);info=target.lstat()
        if stat.S_ISLNK(info.st_mode):
            rel=target.relative_to(root).as_posix()
            if rel in seen or len(seen)>=16:raise Refused('TRACKED_LINK_CYCLE')
            seen.add(rel)
            if info.st_uid not in (0,os.geteuid()) or rel not in tracked or tracked[rel][0]!='120000':raise Refused('UNTRACKED_LINK_COMPONENT')
            value=os.fsencode(os.readlink(target))
            if len(value)>8192 or hashlib.sha1(b'blob '+str(len(value)).encode()+b'\0'+value).hexdigest()!=tracked[rel][1]:raise Refused('TRACKED_LINK_BYTES')
            more=list(Path(os.fsdecode(value)).parts)
            if more and more[0]=='/':
                prefix=list(root.parts)
                if more[:len(prefix)]!=prefix:raise Refused('EXTERNAL_TRACKED_TARGET')
                base=[];more=more[len(prefix):]
            parts=more+parts
        elif stat.S_ISDIR(info.st_mode):trusted(info,stat.S_ISDIR);base.append(part)
        else:
            trusted(info,stat.S_ISREG)
            if parts:raise Refused('TRACKED_LINK_COMPONENT')
            rel=target.relative_to(root).as_posix()
            if rel not in tracked or tracked[rel][0] not in ('100644','100755'):raise Refused('UNTRACKED_LINK_TARGET')
            return target
    raise Refused('TRACKED_LINK_TARGET_TYPE')

def payload_contract(root,tracked,deadline):
    rel='scripts/deploy_payload_contract.json'
    if rel not in tracked:return 'LEGACY_PROTECT_ALL'
    def unique(pairs):
        result={}
        for key,value in pairs:
            if key in result:raise Refused('PAYLOAD_CONTRACT_SHAPE')
            result[key]=value
        return result
    try:c=json.loads(_git(root,['show','HEAD:'+rel],deadline,cap=65536),object_pairs_hook=unique)
    except (ValueError,UnicodeError):raise Refused('PAYLOAD_CONTRACT_SHAPE') from None
    keys={'schema','baseline_commit','baseline_tree','default','exclusions','external'}
    if type(c) is not dict or set(c)!=keys or c['schema']!='grid.protected-payload.v1' or c['default']!='PROTECT_ALL_COMMITTED_PATHS' or c['exclusions']!=[] or type(c['exclusions']) is not list:raise Refused('PAYLOAD_CONTRACT_SHAPE')
    if any(type(c[key]) is not str or re.fullmatch('[0-9a-f]{40}',c[key]) is None for key in ('baseline_commit','baseline_tree')):raise Refused('PAYLOAD_CONTRACT_SHAPE')
    if _git(root,['rev-parse',c['baseline_commit']+'^{tree}'],deadline)!=c['baseline_tree']:raise Refused('PAYLOAD_BASELINE')
    _git(root,['merge-base','--is-ancestor',c['baseline_commit'],'HEAD'],deadline)
    if type(c['external']) is not list or len(c['external'])>1000:raise Refused('PAYLOAD_CONTRACT_SHAPE')
    seen=set();roles={'EXTERNAL_EXECUTABLE_WORKFLOW','EXTERNAL_INFERENCE_MODEL','EXTERNAL_MODEL_CACHE','EXTERNAL_OUTPUT_STATE'}
    for row in c['external']:
        if type(row) is not dict or set(row)!={'path','link_oid','declared_target','role','target_integrity','target_owner'}:raise Refused('PAYLOAD_CONTRACT_SHAPE')
        if any(type(v) is not str for v in row.values()) or row['path'] in seen or row['role'] not in roles or row['target_integrity']!='UNRESOLVED' or row['target_owner']!='UNRESOLVED':raise Refused('PAYLOAD_CONTRACT_SHAPE')
        seen.add(row['path'])
        if tracked.get(row['path'])!=('120000',row['link_oid']):raise Refused('PAYLOAD_EXTERNAL_BINDING')
        target=row['declared_target']
        if not target.startswith('/') or len(target)>8192 or target!=target.strip() or any(x in target for x in '\0\r\n') or _git(root,['cat-file','blob',row['link_oid']],deadline)!=target:raise Refused('PAYLOAD_EXTERNAL_BINDING')
    if seen:raise Refused('EXTERNAL_PAYLOAD_POLICY_UNRESOLVED')
    return 'COMMIT_BOUND_PROTECT_ALL'

def working_tree(root,deadline):
    listing=_git(root,['ls-tree','-rz','--full-tree','HEAD'],deadline,cap=1048576)
    entries=listing.split('\0')
    if entries[-1]!='' or len(entries)>100001:raise Refused('TRACKED_TREE_BOUND')
    tracked={}
    for item in entries[:-1]:
        try:meta,rel=item.split('\t',1);mode,kind,oid=meta.split(' ')
        except ValueError:raise Refused('TRACKED_TREE_SHAPE') from None
        tracked[rel]=(mode,oid)
    contract=payload_contract(root,tracked,deadline)
    indexed={}
    listing_index=_git(root,['ls-files','--stage','-z'],deadline,cap=1048576)
    for entry in listing_index.split('\0')[:-1]:
        try:meta,rel=entry.split('\t',1);mode,oid,stage=meta.split(' ')
        except ValueError:raise Refused('INDEX_BINDING') from None
        if stage!='0' or rel in indexed:raise Refused('INDEX_BINDING')
        indexed[rel]=(mode,oid)
    if indexed!=tracked:raise Refused('INDEX_BINDING')
    total=0
    for item in entries[:-1]:
        _budget(deadline)
        try:meta,rel=item.split('\t',1);mode,kind,oid=meta.split(' ')
        except ValueError:raise Refused('TRACKED_TREE_SHAPE') from None
        if kind!='blob' or mode not in ('100644','100755','120000') or re.fullmatch('[0-9a-f]{40}',oid) is None:raise Refused('TRACKED_TREE_KIND')
        if not rel or rel.startswith('/') or any(x in ('','.','..') for x in rel.split('/')):raise Refused('TRACKED_TREE_PATH')
        path=root/rel;directory(path.parent);st=path.lstat()
        if mode=='120000':
            if not stat.S_ISLNK(st.st_mode) or st.st_uid not in (0,os.geteuid()):raise Refused('TRACKED_LINK_OWNER')
            data=os.fsencode(os.readlink(path))
            if len(data)>8192:raise Refused('TRACKED_LINK_BOUND')
            if hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()!=oid:raise Refused('TRACKED_LINK_BYTES')
            tracked_target(root,path,data,tracked)
        else:
            trusted(st,stat.S_ISREG)
            if (mode=='100755' and not st.st_mode&stat.S_IXUSR) or (mode=='100644' and st.st_mode&0o111):raise Refused('TRACKED_EXECUTABLE')
            if st.st_size>33554432:raise Refused('TRACKED_FILE_BOUND')
            total+=st.st_size
            if total>268435456:raise Refused('TRACKED_TOTAL_BOUND')
            fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
            try:
                opened=os.fstat(fd);trusted(opened,stat.S_ISREG)
                if (opened.st_dev,opened.st_ino,opened.st_size)!=(st.st_dev,st.st_ino,st.st_size):raise Refused('TRACKED_REPLACED')
                digest=hashlib.sha1(b'blob '+str(st.st_size).encode()+b'\0');count=0
                while True:
                    _budget(deadline);chunk=os.read(fd,65536)
                    if not chunk:break
                    count+=len(chunk)
                    if count>st.st_size:raise Refused('TRACKED_REPLACED')
                    digest.update(chunk)
                if count!=st.st_size:raise Refused('TRACKED_REPLACED')
            finally:os.close(fd)
            if digest.hexdigest()!=oid:raise Refused('TRACKED_BYTES')
            continue
        if hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()!=oid:raise Refused('TRACKED_LINK_BYTES')
    return len(entries)-1

def identity(root,expected=None,expected_tree=None):
    root=directory(root);deadline=time.monotonic()+10
    git_inputs(root,deadline)
    if _git(root,['rev-parse','--show-toplevel'],deadline)!=str(root):raise Refused('GIT_TOPLEVEL')
    if _git(root,['rev-parse','--absolute-git-dir'],deadline)!=str(root/'.git'):raise Refused('GIT_DIRECTORY')
    if _git(root,['rev-parse','--is-bare-repository'],deadline)!='false':raise Refused('GIT_BARE')
    value=_git(root,['show','-s','--format=%H:%T','HEAD'],deadline)
    if re.fullmatch('[0-9a-f]{40}:[0-9a-f]{40}',value) is None:raise Refused('GIT_IDENTITY')
    head,tree=value.split(':')
    if expected is not None and (not re.fullmatch('[0-9a-f]{40}',expected) or head!=expected):raise Refused('GIT_EXPECTED')
    if expected_tree is not None and (not re.fullmatch('[0-9a-f]{40}',expected_tree) or tree!=expected_tree):raise Refused('GIT_EXPECTED_TREE')
    count=working_tree(root,deadline)
    if _git(root,['ls-files','--others','--exclude-standard','-z'],deadline,cap=1048576):raise Refused('UNTRACKED_INPUT')
    return {'root':str(root),'head':head,'tree':tree,'tracked_files':count,'working_bytes':'TRACKED_BYTES_CHECKED','external_runtime':'NOT_ATTESTED'}

def repository(live,path,expected=None,expected_tree=None):
    return identity(release(live,path),expected,expected_tree)

def candidate(live,path):
    root=release(live,path)
    if os.path.lexists(root/'.git'):return pin_inputs(root)
    if any(root.iterdir()):raise Refused('CANDIDATE_NOT_EMPTY')
    return {'root':str(root),'state':'PROTECTED_EMPTY_BEFORE_BUILD'}

def pin_inputs(root):
    root=directory(root);deadline=time.monotonic()+10;git_inputs(root,deadline)
    # The legacy pin operation also accepts a genuinely empty git-init target.
    # Missing/corrupt committed history is not silently treated as unborn.
    if (root/'.git/HEAD').stat().st_size>4096:raise Refused('UNBORN_HEAD')
    head=(root/'.git/HEAD').read_text(encoding='ascii')
    if re.fullmatch(r'ref: refs/heads/[A-Za-z0-9][A-Za-z0-9._/-]*\n',head) is not None:
        ref=head[5:].strip()
        _git(root,['check-ref-format',ref],deadline)
        if any(part in ('','.','..') for part in ref.split('/')):raise Refused('UNBORN_HEAD')
        if not os.path.lexists(root/'.git'/ref):
            packed=root/'.git/packed-refs'
            if packed.exists() and packed.stat().st_size>1048576:raise Refused('UNBORN_NONEMPTY')
            if packed.exists() and any(line and not line.startswith('#') for line in packed.read_text(encoding='ascii').splitlines()):raise Refused('UNBORN_NONEMPTY')
            for folder in (root/'.git/refs',root/'.git/objects'):
                for current,dirs,files in os.walk(folder):
                    _budget(deadline)
                    if files:raise Refused('UNBORN_NONEMPTY')
            if _git(root,['rev-parse','--show-toplevel'],deadline)!=str(root) or _git(root,['rev-parse','--absolute-git-dir'],deadline)!=str(root/'.git') or _git(root,['rev-parse','--is-bare-repository'],deadline)!='false':raise Refused('GIT_TOPLEVEL')
            if _git(root,['ls-files','--stage','-z'],deadline) or any(x.name!='.git' for x in root.iterdir()):raise Refused('UNBORN_NONEMPTY')
            return {'root':str(root),'state':'PROTECTED_UNBORN_BEFORE_FETCH'}
    return identity(root)

def pin(root,url,expected):
    pin_inputs(root)
    if re.fullmatch('[0-9a-f]{40}',expected) is None:raise Refused('GIT_EXPECTED')
    try:u=urlsplit(url);port=u.port
    except ValueError:raise Refused('FETCH_URL') from None
    if len(url)>4096 or any(c in url for c in '\r\n\0') or u.scheme!='https' or u.hostname!='github.com' or port is not None or u.path!='/3pacs/GRID.git' or u.query or u.fragment or (u.username is not None and (u.username!='x-access-token' or not u.password)):raise Refused('FETCH_URL')
    deadline=time.monotonic()+75;old=os.umask(0o077);os.umask(old|0o077)
    try:
        with tempfile.TemporaryDirectory(prefix='.source-pin-home-',dir=Path(root)/'.git') as home:
            _git(Path(root),['fetch','--no-tags','--no-recurse-submodules',url,expected],deadline,cap=32768,network=True,command_timeout=60,home=home)
            _git(Path(root),['reset','--hard',expected],deadline,cap=32768,command_timeout=10)
    finally:os.umask(old)
    return identity(root,expected)

def marker_path(parent,name):
    parent=directory(parent)
    if name not in MARKERS:raise Refused('MARKER_NAME')
    return parent/name

def marker_read(parent,name,missing_ok=False):
    path=marker_path(parent,name)
    try:fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    except FileNotFoundError:
        if missing_ok:return None
        raise Refused('MARKER_MISSING') from None
    try:
        st=os.fstat(fd);trusted(st,stat.S_ISREG)
        if st.st_size>2048:raise Refused('MARKER_BOUND')
        b=os.read(fd,2049)
        if len(b)>2048 or b'\0' in b:raise Refused('MARKER_BOUND')
        try:return b.decode('utf-8')
        except UnicodeError:raise Refused('MARKER_ENCODING') from None
    finally:os.close(fd)

def marker_write(parent,name,value):
    if name in ('.lock','.runtime-preservation','.runtime-retention'):raise Refused('MARKER_NOT_ORDINARY_WRITER')
    path=marker_path(parent,name);marker_read(parent,name,True)
    b=value.encode('utf-8')
    if len(b)>2048 or b'\0' in b:raise Refused('MARKER_BOUND')
    fd=None;temporary=None
    try:
        fd,temporary=tempfile.mkstemp(prefix='.protected-marker-',dir=path.parent)
        trusted(os.fstat(fd),stat.S_ISREG)
        with os.fdopen(fd,'wb') as f:fd=None;f.write(b);f.flush();os.fsync(f.fileno())
        os.replace(temporary,path);temporary=None
        dfd=os.open(path.parent,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW)
        try:os.fsync(dfd)
        finally:os.close(dfd)
    finally:
        if fd is not None:os.close(fd)
        if temporary is not None:os.unlink(temporary)

def marker_clear(parent,label):
    if re.fullmatch('[A-Za-z0-9][A-Za-z0-9._-]*',label) is None:raise Refused('MARKER_LABEL')
    text=marker_read(parent,'.activation-in-progress',True)
    if text is not None and text.startswith('label='+label+' '):
        os.unlink(marker_path(parent,'.activation-in-progress'));return True
    return False

def prepare(parent):
    path=lexical(parent);directory(path.parent)
    try:os.mkdir(path,0o700)
    except FileExistsError:pass
    directory(path)
    lock=marker_path(path,'.lock')
    try:fd=os.open(lock,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
    except FileExistsError:
        fd=os.open(lock,os.O_WRONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    try:trusted(os.fstat(fd),stat.S_ISREG)
    finally:os.close(fd)
    for name in MARKERS-{'.lock'}:marker_read(path,name,True)

def binding(live,cwd,expected):
    want=repository(live,live,expected)
    got=repository(live,cwd,expected)
    if got['root']!=want['root']:raise Refused('SERVICE_BINDING')
    return got

def main(args=None):
    args=sys.argv[1:] if args is None else args
    try:
        op=args[0]
        if op=='prepare' and len(args)==2:prepare(args[1])
        elif op=='directory' and len(args)==2:directory(args[1])
        elif op=='identity' and len(args) in (2,3):print(json.dumps(identity(args[1],args[2] if len(args)==3 else None),sort_keys=True))
        elif op=='repository' and len(args) in (3,4,5):print(json.dumps(repository(*args[1:]),sort_keys=True))
        elif op=='candidate' and len(args)==3:print(json.dumps(candidate(*args[1:]),sort_keys=True))
        elif op=='pin' and len(args)==4:print(json.dumps(pin(*args[1:]),sort_keys=True))
        elif op=='binding' and len(args)==4:print(json.dumps(binding(*args[1:]),sort_keys=True))
        elif op=='marker-read' and len(args)==3:sys.stdout.write(marker_read(*args[1:]))
        elif op=='marker-write' and len(args)==4:marker_write(*args[1:])
        elif op=='marker-clear' and len(args)==3:print(json.dumps({'cleared':marker_clear(*args[1:])}))
        else:raise Refused('ARGUMENTS')
        return 0
    except (Refused,OSError,IndexError) as e:
        code=str(e) if isinstance(e,Refused) else 'FILESYSTEM'
        print('SOURCE_POLICY_REFUSED '+code,file=sys.stderr);return 5
    except BaseException:
        print('SOURCE_POLICY_REFUSED UNEXPECTED',file=sys.stderr);return 5

if __name__=='__main__':raise SystemExit(main())
