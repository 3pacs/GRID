"""Explicit equity-direction polarity for GRID ``feature_registry`` features.

Convention (oriented toward broad US equities):
    +1 : higher feature value is bullish for equities (e.g. breadth, equity price,
         expansionary macro activity, falling spreads via corporate bond ETF price).
    -1 : higher feature value is bearish for equities (e.g. VIX / volatility,
         credit spreads, unemployment / jobless claims, systemic stress, conflict).
     0 : non-directional or regime-ambiguous (e.g. interest-rate levels/slopes,
         FX pairs, commodities, unsigned trading volume, celestial indicators).

Resolution order:
    1. Exact name match in :data:`FEATURE_POLARITY`.
    2. Explicit dynamic template pattern in :data:`PATTERN_POLARITY` (for
       per-ticker generated series such as ``<ticker>_iv_atm`` or ``wn_*``).
    3. Unambiguous family default in :data:`FAMILY_DEFAULT_POLARITY`.
    4. Fail closed: ``(0, "unknown")`` — excluded from directional votes and
       coherence so newly added features can never silently vote with the wrong
       sign.
"""

