def resolve_feature_polarity(name: str, family: str | None = None) -> tuple[int, str]:
    """Return ``(polarity, source)`` for ``(name, family)``.

    ``polarity`` is one of ``-1``, ``0``, ``+1``.
    ``source`` is one of ``"feature"``, ``"pattern"``, ``"family"``, or ``"unknown"``.
    Unknown features fail closed to ``(0, "unknown")`` so they cannot silently vote.
    """
    key = (name or "").strip().lower()
    if key in FEATURE_POLARITY:
        return FEATURE_POLARITY[key], "feature"

    for pattern, polarity in PATTERN_POLARITY:
        if pattern.search(key):
            return polarity, "pattern"

    fam = (family or "").strip().lower()
    if fam in FAMILY_DEFAULT_POLARITY:
        return FAMILY_DEFAULT_POLARITY[fam], "family"

    return 0, "unknown"


def get_feature_polarity(name: str, family: str | None = None) -> int:
    """Return equity-direction polarity in ``{-1, 0, +1}`` for ``(name, family)``."""
    polarity, _ = resolve_feature_polarity(name, family)
    return polarity
